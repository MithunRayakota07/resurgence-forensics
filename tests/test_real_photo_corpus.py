"""
The real-photograph corpus builder.

The synthetic corpus is generated by us, which has always been the softest
part of the evidence. This builder lays real photographs out on a disk image
with real photographs as the surrounding junk, so the result is a claim about
photographs rather than about our own generator.

These tests use generated JPEGs written to disk as stand-ins, so the suite
still runs from a clean clone with no photo library present. What they cover
is the builder's machinery -- selection, layout, ground truth -- not the
quality of any particular photo set.
"""

from __future__ import annotations

import io
import json
import os

import pytest
from PIL import Image

from carve.blocks import SOI, ClusterView
from corpus.generate.real_photos import (RealPhotoFiller, build_easy, build_hard,
                                         find_photos, usable)
from corpus.generate.synthetic import CLUSTER, encode_jpeg, make_photo


@pytest.fixture(scope="module")
def photo_dir(tmp_path_factory):
    """A folder of baseline JPEGs big enough to fragment, plus two rejects."""
    d = tmp_path_factory.mktemp("photos")
    for i in range(8):
        # 900x700 at high quality lands comfortably above the 6-cluster floor
        data = encode_jpeg(make_photo(900, 700, seed=i + 1), quality=92)
        (d / ("photo_%02d.jpg" % i)).write_bytes(data)

    # a file too small to fragment
    (d / "tiny.jpg").write_bytes(encode_jpeg(make_photo(64, 64, seed=99), quality=30))

    # a progressive JPEG, which the decoder does not support
    buf = io.BytesIO()
    make_photo(900, 700, seed=50).save(buf, format="JPEG", quality=92, progressive=True)
    (d / "progressive.jpg").write_bytes(buf.getvalue())

    return d


# --------------------------------------------------------------------------
# selection
# --------------------------------------------------------------------------

def test_finds_every_jpeg(photo_dir):
    assert len(find_photos(str(photo_dir))) == 10


def test_accepts_a_baseline_photo(photo_dir):
    got = usable(str(photo_dir / "photo_00.jpg"))
    assert got is not None
    data, mcus = got
    assert mcus > 0
    assert len(data) >= 6 * CLUSTER


def test_rejects_a_progressive_jpeg(photo_dir):
    """
    Baseline only. Progressive scans are not implemented, and silently
    accepting them would produce a misleading pass rate.
    """
    assert usable(str(photo_dir / "progressive.jpg")) is None


def test_rejects_a_photo_too_small_to_fragment(photo_dir):
    assert usable(str(photo_dir / "tiny.jpg")) is None


def test_rejects_a_file_that_is_not_a_jpeg(tmp_path):
    f = tmp_path / "notes.jpg"
    f.write_bytes(b"this is not a jpeg" * 2000)
    assert usable(str(f)) is None


# --------------------------------------------------------------------------
# filler
