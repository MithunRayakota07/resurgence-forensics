def _photos(photo_dir, n=6):
    return [usable(str(photo_dir / ("photo_%02d.jpg" % i)))[0] for i in range(n)]


def test_filler_needs_at_least_one_usable_decoy():
    with pytest.raises(SystemExit):
        RealPhotoFiller([b"tiny"], seed=1)


def test_filler_decoy_bodies_carry_no_header(photo_dir):
    """
    Decoys are stripped of their first 1024 bytes. A decoy that kept its SOI
    would be a real file to carve, not filler, and would corrupt ground truth.
    """
    f = RealPhotoFiller(_photos(photo_dir), seed=1)
    for body in f.decoy_bodies:
        assert not body.startswith(SOI)


def test_filler_produces_full_clusters(photo_dir):
    f = RealPhotoFiller(_photos(photo_dir), seed=1)
    for _ in range(50):
        assert len(f.cluster()) == CLUSTER


