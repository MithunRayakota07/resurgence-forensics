@pytest.fixture(scope="module")
def built(photo_dir, tmp_path_factory):
    out = tmp_path_factory.mktemp("images")
    photos = [usable(str(photo_dir / ("photo_%02d.jpg" % i)))[0] for i in range(8)]
    evidence = [("photo_00.jpg", photos[0]), ("photo_01.jpg", photos[1]),
                ("photo_02.jpg", photos[2])]
    decoys = photos[3:]
    easy = build_easy(str(out), evidence, decoys, 2048, seed=1)
    hard = build_hard(str(out), evidence, decoys, 2048, seed=1)
    return easy, hard


def test_hard_layout_contains_a_backward_jump(built):
    """The whole point of the hard case: the header's successor sits earlier
    on the disk, which is outside a forward-only carver's search space."""
    _, (_, manifest) = built
    order = manifest["files"][0]["cluster_order"]
    assert any(b < a for a, b in zip(order, order[1:]))


def test_manifest_cluster_order_matches_the_fragments(built):
    for _, manifest in built:
        for f in manifest["files"]:
            rebuilt = []
            for fr in sorted(f["fragments"], key=lambda d: d["fragment"]):
                rebuilt.extend(range(fr["start_cluster"],
                                     fr["start_cluster"] + fr["n_clusters"]))
            assert f["cluster_order"] == rebuilt


def test_manifest_records_a_real_source(built):
    for _, manifest in built:
        assert manifest["source"] == "real photographs"


def test_easy_image_holds_two_files_and_hard_holds_one(built):
    (_, easy), (_, hard) = built
    assert len(easy["files"]) == 2
    assert len(hard["files"]) == 1


def test_only_the_evidence_files_look_like_headers(built):
    """
    Decoy filler must not produce spurious JPEG headers at cluster boundaries,
    or the carver would chase files that do not exist and ground truth would
    be wrong.
    """
    for path, manifest in built:
        found = ClusterView(path).find_jpeg_headers()
        expected = sorted(f["cluster_order"][0] for f in manifest["files"])
        assert sorted(found) == expected


